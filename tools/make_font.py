#!/usr/bin/env python3
"""Build the glyph atlas the watch uses to draw the message onto the locket.

makesweet draws locket text in Arial (72pt, black). Arial can't be redistributed, so this
uses Liberation Sans, which has the same metrics (assets/fonts, SIL OFL 1.1).

Each glyph is rendered at 4x and box-filtered down to ATLAS_EM px per em, giving
antialiased coverage, stored at 4 bits per pixel (rows padded to whole bytes).

Outputs:
  resources/font_atlas.bin   glyph bitmaps, concatenated
  src/c/font_data.h          glyph table (code point, box, bearing, advance, offset)

Usage: python3 tools/make_font.py     (needs Pillow + numpy)
"""
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / "assets" / "fonts" / "LiberationSans-Regular.ttf"
ATLAS = ROOT / "resources" / "font_atlas.bin"
HEADER = ROOT / "src" / "c" / "font_data.h"

ATLAS_EM = 32  # px per em in the atlas; the watch scales from this
SUPERSAMPLE = 4

# Printable ASCII, Latin-1, curly quotes, and a few symbols that suit the locket.
CODEPOINTS = (list(range(0x20, 0x7F)) + list(range(0xA1, 0x100)) +
              [0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x2665, 0x2022])


def main():
    big = ImageFont.truetype(str(FONT), ATLAS_EM * SUPERSAMPLE)
    ascent, descent = big.getmetrics()
    S = SUPERSAMPLE
    glyphs = []
    blob = bytearray()
    for cp in CODEPOINTS:
        ch = chr(cp)
        if big.getmask(ch).getbbox() is None and cp != 0x20:
            if not big.getlength(ch):
                continue
        advance = big.getlength(ch) / S
        # Render with the pen at (pad, baseline) on a canvas big enough for any bearing.
        pad = ATLAS_EM * S
        canvas = Image.new("L", (ATLAS_EM * S * 4, ATLAS_EM * S * 3), 0)
        ImageDraw.Draw(canvas).text((pad, pad + ascent), ch, font=big, fill=255, anchor="ls")
        a = np.asarray(canvas).astype(np.float32) / 255
        ys, xs = np.nonzero(a > 0)
        if len(xs) == 0:
            glyphs.append((cp, 0, 0, 0, 0, advance, len(blob)))
            continue
        # Align the box to the supersampling grid relative to the pen so the downsampled
        # bitmap's origin is an integer number of atlas px from the pen.
        x0 = pad + ((xs.min() - pad) // S) * S
        y0 = pad + ascent + ((ys.min() - pad - ascent) // S) * S
        x1 = pad + -(-(xs.max() + 1 - pad) // S) * S
        y1 = pad + ascent + -(-(ys.max() + 1 - pad - ascent) // S) * S
        box = a[y0:y1, x0:x1]
        h, w = box.shape[0] // S, box.shape[1] // S
        cov = box.reshape(h, S, w, S).mean((1, 3))
        q = np.clip(np.rint(cov * 15), 0, 15).astype(np.uint8)
        if w % 2:
            q = np.pad(q, ((0, 0), (0, 1)))
        packed = (q[:, 0::2] << 4) | q[:, 1::2]
        xoff = (x0 - pad) // S
        yoff = (y0 - pad - ascent) // S  # top of the box relative to the baseline
        glyphs.append((cp, w, h, xoff, yoff, advance, len(blob)))
        blob += packed.tobytes()

    ATLAS.write_bytes(bytes(blob))
    out = [
        "// Generated by tools/make_font.py, do not edit.",
        "#pragma once", "",
        "#include <pebble.h>", "",
        "// Liberation Sans Regular (metric-compatible with Arial, which makesweet uses).",
        f"#define FONT_ATLAS_EM {ATLAS_EM}",
        f"#define FONT_ASCENT_16 {round(ascent / S * 16)}  // 1/16 px at FONT_ATLAS_EM",
        f"#define FONT_DESCENT_16 {round(descent / S * 16)}",
        f"#define FONT_GLYPH_COUNT {len(glyphs)}",
        f"#define FONT_MAX_GLYPH_BYTES {max(((w + 1) // 2) * h for _, w, h, *_ in glyphs)}", "",
        "// Bitmap: h rows of ceil(w / 2) bytes, 4-bit coverage, high nibble first, at `offset`",
        "// in RESOURCE_ID_FONT_ATLAS. xoff/yoff place its top-left relative to the pen on the",
        "// baseline. Sorted by code point.",
        "typedef struct {",
        "  uint16_t code;",
        "  uint8_t w, h;",
        "  int8_t xoff, yoff;",
        "  uint16_t advance_16;",
        "  uint16_t offset;",
        "} FontGlyph;", "",
        "static const FontGlyph FONT_GLYPHS[FONT_GLYPH_COUNT] = {",
    ]
    for cp, w, h, xoff, yoff, adv, off in glyphs:
        out.append(f"  {{ 0x{cp:04X}, {w}, {h}, {xoff}, {yoff}, {round(adv * 16)}, {off} }},")
    out += ["};", ""]
    HEADER.write_text("\n".join(out))
    print(f"{len(glyphs)} glyphs, atlas {len(blob)} bytes, ascent {ascent / S} descent {descent / S}")


if __name__ == "__main__":
    main()
