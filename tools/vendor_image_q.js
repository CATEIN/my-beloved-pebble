#!/usr/bin/env node
// Packs image-q (https://github.com/ibezkrovnyi/image-quantization, MIT) for the settings
// page as a plain script that defines `imageq`. The build inlines it into the page.
//
// Usage: npm install && node tools/vendor_image_q.js
var fs = require('fs');
var path = require('path');

var root = path.join(__dirname, '..');
var pkgDir = path.join(root, 'node_modules', 'image-q');
var version = require(path.join(pkgDir, 'package.json')).version;
var src = fs.readFileSync(path.join(pkgDir, 'dist', 'cjs', 'image-q.cjs'), 'utf8');
var license = fs.readFileSync(path.join(pkgDir, 'LICENSE'), 'utf8');

if (/<\/script/i.test(src)) {
  throw new Error('image-q contains </script>, which would end the inlined script early');
}

var out = '// Generated by tools/vendor_image_q.js from image-q ' + version + ', do not edit.\n' +
  '//\n' + license.trim().split('\n').map(function (l) { return ('// ' + l).trimEnd(); }).join('\n') +
  '\n\nvar imageq = (function () {\nvar module = { exports: {} }, exports = module.exports;\n' +
  src + '\nreturn module.exports;\n})();\n';

var dest = path.join(root, 'src', 'settings', 'vendor', 'image-q.js');
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log('wrote ' + path.relative(root, dest) + ' (' + out.length + ' bytes)');
